def a3_a4(d, meta, out):
    from common_data import fixed_control
    from common_train_data import TrainingData
    td = TrainingData(d.dataset)
    seed = td.receipt['split_seed']
    ctrl = td.control.toarray().astype(np.float32)
    pool_mean = ctrl.mean(axis=0, dtype=np.float64)
    rng = np.random.default_rng(1)
    # control pool spread
    dev = ctrl - pool_mean
    per_cell_rms = np.sqrt((dev.astype(np.float64) ** 2).mean(axis=1))
    a, b = rng.integers(0, len(ctrl), 20000), rng.integers(0, len(ctrl), 20000)
    pair_rms = np.sqrt(((ctrl[a] - ctrl[b]).astype(np.float64) ** 2).mean(axis=1))
    # D1 pairings (all 15 epochs) -- note: hashed on the *split* seed, so identical across training seeds
    ids = td.train_ids
    fixed = td.paired
    d1 = np.stack([np.array([fixed_control(td.pool_ids, c, seed, e) for c in ids]) for e in range(1, 16)])
    changed = (d1 != fixed[None]).mean(axis=1)
    distinct_per_cell = np.array([len(set(col)) for col in np.vstack([fixed[None], d1]).T])
    sub = rng.choice(len(ids), 5000, replace=False)
    swap_rms = np.sqrt(((ctrl[fixed[sub]] - ctrl[d1[0, sub]]).astype(np.float64) ** 2).mean(axis=1))
    # per train intervention: offset of the paired-control mean from the pool mean
    rows_a3 = []
    resp_by = dict(zip(d.train_names, d.train_resp))
    for c in sorted(td.train_rows):
        r = td.train_rows[c]
        off_fixed = ctrl[fixed[r]].mean(axis=0, dtype=np.float64) - pool_mean
        off_d1 = np.mean([ctrl[d1[e, r]].mean(axis=0, dtype=np.float64) for e in range(15)], axis=0) - pool_mean
        off_d1_epoch = np.mean([np.sqrt(np.mean((ctrl[d1[e, r]].mean(axis=0, dtype=np.float64) - pool_mean) ** 2))
                                for e in range(15)])
        eff = float(np.sqrt(np.mean(resp_by[c] ** 2)))
        rows_a3.append(dict(train_condition=c, n_cells=len(r), n_targets=len(td.train[c]['targets']),
                            train_effect_rms=eff,
                            fixed_pair_mean_offset_rms=float(np.sqrt(np.mean(off_fixed ** 2))),
                            d1_single_epoch_offset_rms_mean=float(off_d1_epoch),
                            d1_15epoch_pooled_offset_rms=float(np.sqrt(np.mean(off_d1 ** 2))),
                            fixed_offset_over_effect=float(np.sqrt(np.mean(off_fixed ** 2)) / eff)))
    save(out / 'A3_train_pairing.tsv', rows_a3)
    hist_d1 = [e['changed_pairs'] for e in d.results['D1']['history']]
    tl = {k: [e['train_loss'] for e in d.results[k]['history']] for k in ('M0', 'D1', 'D2', 'D0-seed1', 'D0-seed2', 'D1-seed1', 'D1-seed2')}
    a3_summary = dict(
        pairing_seed='split seed (26); D1 resampled pairs identical across training seeds 0-2',
        control_pool_cells=len(ctrl), train_cells=len(ids),
        fixed_unique_controls_used=int(len(np.unique(fixed))),
        changed_pairs_logged_per_epoch=[min(hist_d1), max(hist_d1)],
        changed_pairs_recomputed=[float(changed.min()), float(changed.max())],
        distinct_controls_per_treated_cell_over_fixed_plus_15=dict(
            mean=float(distinct_per_cell.mean()), min=int(distinct_per_cell.min())),
        control_cell_rms_dev_from_pool_mean=dict(mean=float(per_cell_rms.mean()), median=float(np.median(per_cell_rms))),
        random_control_pair_rms_distance=dict(mean=float(pair_rms.mean())),
        fixed_vs_d1_epoch1_control_rms_distance=dict(mean=float(swap_rms.mean())),
        control_gene_sd_mean=float(d.ctrl_sd.mean()),
        train_effect_rms=dict(median=float(np.median([r['train_effect_rms'] for r in rows_a3])),
                              min=float(min(r['train_effect_rms'] for r in rows_a3))),
        fixed_pair_offset_rms=dict(median=float(np.median([r['fixed_pair_mean_offset_rms'] for r in rows_a3])),
                                   max=float(max(r['fixed_pair_mean_offset_rms'] for r in rows_a3))),
        fixed_offset_over_effect=dict(median=float(np.median([r['fixed_offset_over_effect'] for r in rows_a3])),
                                      max=float(max(r['fixed_offset_over_effect'] for r in rows_a3))),
        spearman_fixed_offset_vs_ncells=spear([r['fixed_pair_mean_offset_rms'] for r in rows_a3],
                                              [r['n_cells'] for r in rows_a3]),
        train_loss_by_epoch=tl)

    # A4: D2 exposure schedule, reproduced exactly from the saved schedule function
    exp_d2 = {c: np.zeros(15) for c in td.train_rows}
    uniq_d2 = {c: np.zeros(15) for c in td.train_rows}
    seen_ever = {c: set() for c in td.train_rows}
    single_share = []
    for e in range(1, 16):
        rows, _ = td.schedule('D2', 0, e)
        names = td.train_names[rows]
        single_share.append(float(np.mean([len(td.train[c]['targets']) == 1 for c in names])))
        for c in td.train_rows:
            sel = rows[names == c]
            exp_d2[c][e - 1] = len(sel)
            uniq_d2[c][e - 1] = len(np.unique(sel))
            seen_ever[c].update(sel.tolist())
    d0_single = float(np.mean([len(td.train[c]['targets']) == 1 for c in td.train_names]))
    rows_a4 = []
    for c, r in td.train_rows.items():
        n = len(r)
        rows_a4.append(dict(train_condition=c, n_targets=len(td.train[c]['targets']), n_cells=n,
                            d0_exposures_per_epoch=n, d2_exposures_per_epoch=float(exp_d2[c].mean()),
                            exposure_ratio_d2_over_d0=float(exp_d2[c].mean() / n),
                            d2_unique_cells_per_epoch=float(uniq_d2[c].mean()),
                            d2_repeat_per_unique_cell_per_epoch=float(exp_d2[c].mean() / uniq_d2[c].mean()),
                            d2_fraction_cells_seen_15ep=len(seen_ever[c]) / n))
    save(out / 'A4_train_exposure.tsv', rows_a4)
    by = {r['train_condition']: r for r in rows_a4}
    flags_d0 = sum(len(td.train[c]['targets']) for c in td.train_names)
    a4_summary = dict(
        d0_single_cell_share=d0_single, d2_single_exposure_share_mean=float(np.mean(single_share)),
        d0_target_flags_per_epoch=int(flags_d0),
        d2_target_flags_logged=[e['target_flags'] for e in d.results['D2']['history']][:3],
        n_train_upsampled=int(sum(r['exposure_ratio_d2_over_d0'] > 1 for r in rows_a4)),
        n_train_downsampled=int(sum(r['exposure_ratio_d2_over_d0'] < 1 for r in rows_a4)),
        max_repeat_per_cell_per_epoch=float(max(r['d2_repeat_per_unique_cell_per_epoch'] for r in rows_a4)),
        cells_never_seen_in_d2_15ep=int(sum(round((1 - r['d2_fraction_cells_seen_15ep']) * r['n_cells'])
                                            for r in rows_a4)),
        single_vs_double_exposure=dict(
            d0_single=sum(r['n_cells'] for r in rows_a4 if r['n_targets'] == 1),
            d0_double=sum(r['n_cells'] for r in rows_a4 if r['n_targets'] == 2),
            d2_single=sum(r['d2_exposures_per_epoch'] for r in rows_a4 if r['n_targets'] == 1),
            d2_double=sum(r['d2_exposures_per_epoch'] for r in rows_a4 if r['n_targets'] == 2)),
        n_train_single=sum(r['n_targets'] == 1 for r in rows_a4), n_train_double=sum(r['n_targets'] == 2 for r in rows_a4))

    # validation-level relations for D1-D0 and D2-D0, with seed noise floor from D0 seeds
    bv = d.bestval
    val_rows = []
    for m in meta:
        c = m['condition']
        related = [n for n, v in td.train.items() if set(v['targets']) & set(d.val[c]['targets'])]
        d0s = [bv[k][c]['delta_rmse'] for k in ('M0', 'D0-seed1', 'D0-seed2')]
        d1s = [bv[k][c]['delta_rmse'] for k in ('D1', 'D1-seed1', 'D1-seed2')]
        val_rows.append(dict(
            condition=c, kind=m['kind'], seen_group=m['seen_group'], n_cells=m['n_cells'], effect_rms=m['effect_rms'],
            tertile=m['tertile'], nearest_train_response_corr=m['nearest_train_response_corr'],
            n_related_train=len(related), related_train_cells=m['related_train_cells'],
            related_log2_exposure_ratio=float(np.mean([np.log2(by[n]['exposure_ratio_d2_over_d0']) for n in related]))
            if related else np.nan,
            related_mean_fixed_offset=float(np.mean([r['fixed_pair_mean_offset_rms'] for r in rows_a3
                                                     if r['train_condition'] in related])) if related else np.nan,
            d0_seed0=d0s[0], d0_seed_mean=float(np.mean(d0s)), d0_seed_sd=float(np.std(d0s, ddof=1)),
            d1_seed0=d1s[0], d1_seed_mean=float(np.mean(d1s)), d1_seed_sd=float(np.std(d1s, ddof=1)),
            d2_seed0=bv['D2'][c]['delta_rmse'],
            d1_minus_d0_seed0=d1s[0] - d0s[0], d1_minus_d0_3seed=float(np.mean(d1s) - np.mean(d0s)),
            d2_minus_d0_seed0=bv['D2'][c]['delta_rmse'] - d0s[0],
            d2_minus_d0_3seedmean=bv['D2'][c]['delta_rmse'] - float(np.mean(d0s)),
            d2_outside_d0_seed_range=bool(not (min(d0s) <= bv['D2'][c]['delta_rmse'] <= max(d0s)))))
    save(out / 'A3_A4_val_interventions.tsv', val_rows)
    rel = []
    for target in ('d1_minus_d0_seed0', 'd1_minus_d0_3seed', 'd2_minus_d0_seed0', 'd2_minus_d0_3seedmean'):
        y = [r[target] for r in val_rows]
        for cov in ('effect_rms', 'n_cells', 'nearest_train_response_corr', 'related_train_cells',
                    'related_log2_exposure_ratio', 'related_mean_fixed_offset', 'd0_seed_sd'):
            rel.append(dict(response=target, covariate=cov, **spear([r[cov] for r in val_rows], y)))
        for key in ('kind', 'tertile', 'seen_group'):
            for lvl in sorted({r[key] for r in val_rows}):
                x = [r[target] for r in val_rows if r[key] == lvl]
                rel.append(dict(response=target, covariate=f'{key}={lvl}', rho=float(np.mean(x)), p=np.nan, n=len(x),
                                note='mean difference in subgroup'))
    save(out / 'A3_A4_relations.tsv', rel)
    sd = np.array([r['d0_seed_sd'] for r in val_rows])
    noise = dict(
        d0_seed_pooled_val=[float(np.mean([bv[k][c]['delta_rmse'] for c in d.names])) for k in ('M0', 'D0-seed1', 'D0-seed2')],
        d1_seed_pooled_val=[float(np.mean([bv[k][c]['delta_rmse'] for c in d.names])) for k in ('D1', 'D1-seed1', 'D1-seed2')],
        d0_per_intervention_seed_sd_median=float(np.median(sd)),
        frac_abs_d1_minus_d0_seed0_gt_2sd=float(np.mean(np.abs([r['d1_minus_d0_seed0'] for r in val_rows]) > 2 * sd)),
        frac_abs_d2_minus_d0_seed0_gt_2sd=float(np.mean(np.abs([r['d2_minus_d0_seed0'] for r in val_rows]) > 2 * sd)),
        frac_d2_outside_d0_seed_range=float(np.mean([r['d2_outside_d0_seed_range'] for r in val_rows])),
        n_d2_worse_than_all_d0_seeds=int(sum(r['d2_outside_d0_seed_range'] and r['d2_seed0'] > r['d0_seed_mean']
                                             for r in val_rows)),
        n_d2_better_than_all_d0_seeds=int(sum(r['d2_outside_d0_seed_range'] and r['d2_seed0'] < r['d0_seed_mean']
                                              for r in val_rows)),
        n_d1_3seed_mean_worse=int(sum(r['d1_minus_d0_3seed'] > 0 for r in val_rows)))
    return a3_summary, a4_summary, noise


# ---------------------------------------------------------------- A5
def a5(d, meta, out):
    mby = {m['condition']: m for m in meta}
    groups = subgroups(meta)
    sd = d.ctrl_sd
    per, retr_rows, scan_rows = [], [], []
    alphas = np.round(np.arange(0, 2.0001, 0.01), 2)
    for m in A5_METHODS:
        if m not in d.pred:
            continue
        conds = [c for c in d.names if c in d.pred[m]]
        ix = [d.names.index(c) for c in conds]
        P = np.stack([d.pred[m][c] - d.reference for c in conds])
        T = d.tdelta[ix]
        mu = d.mu
        for i, c in enumerate(conds):
            p, t = P[i], T[i]
            row = dict(method=m, condition=c, delta_rmse=float(np.sqrt(np.mean((p - t) ** 2))),
                       delta_pearson=pear(p, t), centered_pearson=pear(p - mu, t - mu),
                       centered_cosine=float((p - mu) @ (t - mu) / (np.linalg.norm(p - mu) * np.linalg.norm(t - mu)))
                       if np.linalg.norm(p - mu) > 0 else np.nan,
                       slope_through_origin=float(p @ t / (t @ t)),
                       ols_slope=float(np.cov(p, t)[0, 1] / np.var(t, ddof=1)),
                       norm_ratio=float(np.linalg.norm(p) / np.linalg.norm(t)),
                       centered_norm_ratio=float(np.linalg.norm(p - mu) / np.linalg.norm(t - mu)),
                       pred_corr_with_mean_train_effect=pear(p, mu), true_corr_with_mean_train_effect=pear(t, mu),
                       pred_frac_energy_along_mean_train_effect=float((p @ mu) ** 2 / ((p @ p) * (mu @ mu)))
                       if p @ p > 0 else np.nan)
            at = np.abs(t)
            for k in (20, 50, 100):
                top = set(np.argsort(-at, kind='stable')[:k])
                ptop = set(np.argsort(-np.abs(p), kind='stable')[:k]) if np.abs(p).max() > 0 else set()
                row[f'recall_top{k}'] = len(top & ptop) / k
            ok = sd > 0
            zt, zp = np.where(ok, at / np.where(ok, sd, 1), 0), np.where(ok, np.abs(p) / np.where(ok, sd, 1), 0)
            top = set(np.argsort(-zt, kind='stable')[:20])
            ptop = set(np.argsort(-zp, kind='stable')[:20]) if zp.max() > 0 else set()
            row['recall_top20_standardized'] = len(top & ptop) / 20
            # centered top-DE: genes most specific to this perturbation relative to the mean train effect
            ct, cp = np.abs(t - mu), np.abs(p - mu)
            top = set(np.argsort(-ct, kind='stable')[:20])
            ptop = set(np.argsort(-cp, kind='stable')[:20]) if cp.max() > 0 else set()
            row['recall_top20_centered'] = len(top & ptop) / 20
            t20 = np.argsort(-at, kind='stable')[:20]
            row['direction_top20'] = float(np.mean(np.sign(p[t20]) == np.sign(t[t20])))
            per.append(row)
        # retrieval among the conditions this method predicts
        n = len(conds)
        S = np.array([[pear(P[i], T[j]) for j in range(n)] for i in range(n)])
        Sc = np.array([[pear(P[i] - mu, T[j] - mu) for j in range(n)] for i in range(n)])
        Dm = np.array([[np.sqrt(np.mean((P[i] - T[j]) ** 2)) for j in range(n)] for i in range(n)])
        for name, rk in (('pearson', rank_of_true(S)), ('centered_pearson', rank_of_true(Sc)),
                         ('rmse', rank_of_true(Dm, higher_better=False))):
            for i, c in enumerate(conds):
                retr_rows.append(dict(method=m, condition=c, score=name, n_candidates=n, rank=float(rk[i]),
                                      norm_rank=float((rk[i] - 1) / (n - 1))))
        # shrinkage scan: pooled delta RMSE of alpha * predicted delta
        sc = [float(np.mean(np.sqrt(np.mean((a * P - T) ** 2, axis=1)))) for a in alphas]
        best = int(np.argmin(sc))
        for gname in ('all', 'T1_weak', 'T2_mid', 'T3_strong'):
            sel = [i for i, c in enumerate(conds) if c in groups[gname]]
            if not sel:
                continue
            s = [float(np.mean(np.sqrt(np.mean((a * P[sel] - T[sel]) ** 2, axis=1)))) for a in alphas]
            b = int(np.argmin(s))
            scan_rows.append(dict(method=m, subgroup=gname, n=len(sel), rmse_alpha1=s[list(alphas).index(1.0)],
                                  rmse_alpha0=s[0], best_alpha=float(alphas[b]), rmse_best_alpha=s[b],
                                  rmse_alpha0_5=s[list(alphas).index(0.5)],
                                  rel_gain_best_vs_1=(s[list(alphas).index(1.0)] - s[b]) / s[list(alphas).index(1.0)]))
        del best, sc
    save(out / 'A5_per_condition.tsv', per)
    save(out / 'A5_retrieval_per_condition.tsv', retr_rows)
    save(out / 'A5_shrinkage_scan.tsv', scan_rows)

    # pooled + stratified summary
    metrics = ['delta_rmse', 'delta_pearson', 'centered_pearson', 'slope_through_origin', 'ols_slope', 'norm_ratio',
               'centered_norm_ratio', 'recall_top20', 'recall_top50', 'recall_top100', 'recall_top20_standardized',
               'recall_top20_centered', 'direction_top20', 'pred_corr_with_mean_train_effect',
               'true_corr_with_mean_train_effect', 'pred_frac_energy_along_mean_train_effect']
    summ = []
    full = {m for m in A5_METHODS if m in d.pred and len(d.pred[m]) == len(d.names)}
    sub8 = sorted(d.pred['additive'])
    for m in A5_METHODS:
        if m not in d.pred:
            continue
        for gname, conds in list(groups.items()) + [('additive_subset8', sub8)]:
            if m == 'additive' and gname not in ('additive_subset8',):
                continue
            rows = [r for r in per if r['method'] == m and r['condition'] in conds]
            if not rows:
                continue
            s = dict(method=m, subgroup=gname, n=len(rows))
            for k in metrics:
                v = [r[k] for r in rows if r[k] is not None and np.isfinite(r[k])]
                s[k] = float(np.mean(v)) if v else np.nan
                if k == 'slope_through_origin':
                    s['slope_median'] = float(np.median(v)) if v else np.nan
            if m in full or gname == 'additive_subset8':
                for sc in ('pearson', 'centered_pearson', 'rmse'):
                    rr = [r for r in retr_rows if r['method'] == m and r['score'] == sc and r['condition'] in conds]
                    if rr:
                        s[f'retrieval_{sc}_mean_rank'] = float(np.mean([r['rank'] for r in rr]))
                        s[f'retrieval_{sc}_norm_rank'] = float(np.mean([r['norm_rank'] for r in rr]))
                        s[f'retrieval_{sc}_top1'] = float(np.mean([r['rank'] <= 1 for r in rr]))
                        s[f'retrieval_{sc}_top3'] = float(np.mean([r['rank'] <= 3 for r in rr]))
                        s[f'retrieval_{sc}_mrr'] = float(np.mean([1 / r['rank'] for r in rr]))
                        s[f'retrieval_{sc}_n_candidates'] = rr[0]['n_candidates']
            summ.append(s)
    save(out / 'A5_summary.tsv', summ)

    # rank agreement between metrics, over full-coverage primary methods (exclude seed replicates)
    prim = [m for m in ('M0', 'M1', 'M2', 'M3', 'M-random', 'D1', 'D2', 'GEARS', 'linear_go_ridge',
                        'train_mean', 'no_change') if m in full]
    tab = {s['method']: s for s in summ if s['subgroup'] == 'all'}
    order = {}
    for k, sign in (('delta_rmse', 1), ('delta_pearson', -1), ('centered_pearson', -1),
                    ('retrieval_pearson_norm_rank', 1), ('retrieval_centered_pearson_norm_rank', 1),
                    ('recall_top20', -1), ('recall_top20_centered', -1)):
        vals = [sign * tab[m][k] if np.isfinite(tab[m].get(k, np.nan)) else np.inf for m in prim]  # undefined -> last
        order[k] = [prim[i] for i in np.argsort(vals, kind='stable')]
    kt = {}
    base = order['delta_rmse']
    for k, o in order.items():
        r1 = [base.index(m) for m in prim]
        r2 = [o.index(m) for m in prim]
        kt[k] = float(stats.kendalltau(r1, r2).statistic)
    # weak-tertile: how close is no_change to M0?
    weak = {s['method']: s['delta_rmse'] for s in summ if s['subgroup'] == 'T1_weak'}
    strong = {s['method']: s['delta_rmse'] for s in summ if s['subgroup'] == 'T3_strong'}
    allr = {s['method']: s['delta_rmse'] for s in summ if s['subgroup'] == 'all'}
    contrib = {}
    for m in ('M1', 'M2', 'M3', 'M-random', 'D1', 'D2', 'GEARS', 'linear_go_ridge', 'no_change', 'train_mean'):
        if m in full:
            x = {c: next(r['delta_rmse'] for r in per if r['method'] == m and r['condition'] == c) -
                 next(r['delta_rmse'] for r in per if r['method'] == 'M0' and r['condition'] == c) for c in d.names}
            tot = sum(x.values())
            contrib[m] = {g: float(sum(x[c] for c in groups[g]) / tot) if tot else np.nan
                          for g in ('T1_weak', 'T2_mid', 'T3_strong')}
    return dict(method_order=order, kendall_tau_vs_delta_rmse=kt, weak_tertile_delta_rmse=weak,
                strong_tertile_delta_rmse=strong, all_delta_rmse=allr,
                share_of_pooled_gap_vs_M0_by_tertile=contrib,
                effect_tertile_cutpoints=[float(x) for x in np.quantile([m['effect_rms'] for m in meta], [1 / 3, 2 / 3])])


# ---------------------------------------------------------------- H: frozen holdout, descriptive only
def holdout(d, out):
    files = {('D0', 0): 'C0-Norman-v1-scgpt-M0-D0-s26-r0', ('D0', 1): 'F-Norman-v1-scgpt-M0-D0-s26-r1',
             ('D0', 2): 'F-Norman-v1-scgpt-M0-D0-s26-r2', ('D1', 0): 'D-Norman-v1-scgpt-M0-D1-s26-r0',
             ('D1', 1): 'F-Norman-v1-scgpt-M0-D1-s26-r1', ('D1', 2): 'F-Norman-v1-scgpt-M0-D1-s26-r2'}
    sc = {}
    for k, f in files.items():
        j = json.loads((d.study / 'scores' / f'{f}.json').read_text())
        sc[k] = {r['condition']: r for r in j['metrics']['per_condition']}
    train_single = {v['targets'][0] for v in d.train.values() if len(v['targets']) == 1}
    train_any = {g for v in d.train.values() for g in v['targets']}
    conds = sorted(sc[('D0', 0)])
    eff = {c: sc[('D0', 0)][c]['no_change_delta_rmse'] for c in conds}
    q1, q2 = np.quantile(list(eff.values()), [1 / 3, 2 / 3])
    lab = {}
    for c in conds:
        t = d.test[c]['targets']
        seen = (('single_target_in_train_combo' if t[0] in train_any else 'single_target_unseen') if len(t) == 1
                else f'double_{sum(g in train_single for g in t)}of2_train_single')
        lab[c] = dict(kind='single' if len(t) == 1 else 'double', seen_group=seen,
                      tertile='T1_weak' if eff[c] <= q1 else ('T2_mid' if eff[c] <= q2 else 'T3_strong'))
    groups = {'all': conds}
    for key in ('kind', 'seen_group', 'tertile'):
        for c in conds:
            groups.setdefault(lab[c][key], []).append(c)
    rows = []
    for g, cs in groups.items():
        d0 = np.array([[sc[('D0', s)][c]['delta_rmse'] for s in range(3)] for c in cs])
        d1 = np.array([[sc[('D1', s)][c]['delta_rmse'] for s in range(3)] for c in cs])
        gain = (d0 - d1).mean(axis=1)
        rows.append(dict(label='FROZEN_HOLDOUT_DESCRIPTIVE_ONLY', subgroup=g, n=len(cs),
                         d0_mean_3seed=float(d0.mean()), d1_mean_3seed=float(d1.mean()),
                         gain_d0_minus_d1_mean=float(gain.mean()),
                         gain_seed0=float((d0[:, 0] - d1[:, 0]).mean()), gain_seed1=float((d0[:, 1] - d1[:, 1]).mean()),
                         gain_seed2=float((d0[:, 2] - d1[:, 2]).mean()), frac_conditions_d1_better=float(np.mean(gain > 0))))
    save(out / 'H_holdout_D0_D1_subgroups_DESCRIPTIVE.tsv', rows)
    return rows


