def a2(diag, out):
    groups, svd, adam, meta = [], [], [], []
    for f in sorted((diag / 'params').glob('*.json')):
        p = json.loads(f.read_text())
        groups += [g for g in p['groups'] if g['layer'] == 'all' or g['group'].startswith('transformer')]
        svd += p['qkv_svd']
        adam += p['adam']
        h = p['history']
        meta.append(dict(label=p['label'], mode=p['mode'], best_epoch=p['best_epoch'], n_trainable=p['n_trainable'],
                         init_frozen_tensors=p['init_check']['n_frozen_tensors'],
                         init_frozen_mismatched=p['init_check']['n_frozen_mismatched'],
                         cls_decoder_identical=p['init_check']['cls_decoder_identical'],
                         adam_steps=','.join(map(str, p['adam_steps'])), lr_epoch15=p['lr_epoch15'],
                         epoch_seconds=p['epoch_seconds'], peak_gib=p['peak_allocated_gib'],
                         seconds_per_update=p['epoch_seconds'] / p['updates'],
                         train_loss_first=h[0]['train_loss'], train_loss_last=h[-1]['train_loss']))
    save(out / 'A2_param_change_groups.tsv', groups)
    save(out / 'A2_qkv_update_svd.tsv', svd)
    save(out / 'A2_adam_state.tsv', adam)
    save(out / 'A2_run_meta.tsv', meta)
    return dict(groups=groups, svd=svd, adam=adam, meta=meta)


