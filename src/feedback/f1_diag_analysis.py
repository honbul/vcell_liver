def intervention_meta(d):
    train_single = {v['targets'][0] for v in d.train.values() if len(v['targets']) == 1}
    train_any = {g for v in d.train.values() for g in v['targets']}
    train_cells = {c: len(v['treated_ids']) for c, v in d.train.items()}
    resp = d.train_resp
    rows = []
    for i, c in enumerate(d.names):
        t = d.val[c]['targets']
        td = d.tdelta[i]
        effect = float(np.sqrt(np.mean(td ** 2)))
        related = [n for n, v in d.train.items() if set(v['targets']) & set(t)]
        corr = [pear(td, r) for r in resp]
        if len(t) == 1:
            seen = 'single_target_in_train_combo' if t[0] in train_any else 'single_target_unseen'
        else:
            seen = f'double_{sum(g in train_single for g in t)}of2_train_single'
        rows.append(dict(condition=c, n_targets=len(t), kind='single' if len(t) == 1 else 'double',
                         targets='+'.join(t), n_cells=len(d.val[c]['treated_ids']), effect_rms=effect,
                         effect_centered_rms=float(np.sqrt(np.mean((td - d.mu) ** 2))),
                         seen_group=seen, n_targets_seen_any=sum(g in train_any for g in t),
                         n_related_train=len(related),
                         related_train_cells=sum(train_cells[n] for n in related),
                         nearest_train_response_corr=float(np.nanmax(corr)),
                         corr_with_mean_train_response=pear(td, d.mu)))
    eff = np.array([r['effect_rms'] for r in rows])
    med, q1, q2 = np.median(eff), *np.quantile(eff, [1 / 3, 2 / 3])
    for r in rows:
        r['strength'] = 'strong' if r['effect_rms'] > med else 'weak'
        r['tertile'] = 'T1_weak' if r['effect_rms'] <= q1 else ('T2_mid' if r['effect_rms'] <= q2 else 'T3_strong')
    return rows


def subgroups(meta):
    g = {'all': [r['condition'] for r in meta]}
    for key in ('strength', 'tertile', 'kind', 'seen_group'):
        for r in meta:
            g.setdefault(r[key], []).append(r['condition'])
    return g


# ---------------------------------------------------------------- A1
def a1(d, meta, out, rng):
    curves, summ = [], []
    for k in RUNS:
        r = d.results[k]
        h = r['history']
        for e in h:
            curves.append(dict(run=k, epoch=e['epoch'], train_loss=e['train_loss'],
                               val_delta_rmse=e['val_delta_rmse'], changed_pairs=e['changed_pairs'],
                               distinct_examples=e['distinct_examples'], target_flags=e['target_flags'],
                               seconds=e['seconds']))
        v = [e['val_delta_rmse'] for e in h]
        tl = [e['train_loss'] for e in h]
        summ.append(dict(run=k, mode=r['mode'], data_mode=r['data_mode'], seed=r['seed'], lr=r['lr'],
                         n_epochs=len(h), best_epoch=r['best_epoch'], best_val=min(v), val_epoch1=v[0],
                         val_epoch15=v[-1], val_gain_last3=v[-4] - v[-1] if len(v) >= 4 else np.nan,
                         val_epoch15_is_best=bool(v[-1] == min(v)),
                         val_rel_gain_last3=(v[-4] - v[-1]) / v[-4] if len(v) >= 4 else np.nan,
                         train_loss_epoch1=tl[0], train_loss_epoch15=tl[-1],
                         train_gain_last3=tl[-4] - tl[-1], lr_epoch15=r['lr'] * (0.9 if r['model'] == 'scgpt' else 0.5) ** 14,
                         epoch_seconds_total=r['epoch_seconds'], peak_gib=r.get('peak_allocated_gib'),
                         n_trainable=r['model_init'].get('n_trainable')))
    save(out / 'A1_curves.tsv', curves)
    save(out / 'A1_curve_summary.tsv', summ)

    wide = []
    for m in meta:
        c = m['condition']
        row = dict(m)
        for k, bv in d.bestval.items():
            if c in bv:
                row[f'{k}__delta_rmse'] = bv[c]['delta_rmse']
                row[f'{k}__delta_pearson'] = bv[c]['delta_pearson']
                row[f'{k}__top20_recall'] = bv[c]['absolute_delta_top20_recall']
        wide.append(row)
    save(out / 'A1_per_intervention.tsv', wide)

    groups = subgroups(meta)
    mby = {m['condition']: m for m in meta}
    rows, conc = [], []
    for other, ref in COMPARISONS:
        for metric, sign in (('delta_rmse', 1), ('delta_pearson', -1), ('absolute_delta_top20_recall', -1)):
            adv_all = {c: sign * (d.bestval[other][c][metric] - d.bestval[ref][c][metric])
                       for c in d.names if d.bestval[other].get(c, {}).get(metric) is not None
                       and d.bestval[ref].get(c, {}).get(metric) is not None}
            total = sum(adv_all.values())
            for gname, conds in groups.items():
                x = np.array([adv_all[c] for c in conds if c in adv_all])
                if not len(x):
                    continue
                lo, hi = boot_ci(x, rng)
                rows.append(dict(other=other, ref=ref, metric=metric, subgroup=gname, n=len(x),
                                 mean_adv_ref=float(x.mean()), median_adv_ref=float(np.median(x)),
                                 ci95_low=lo, ci95_high=hi, ref_better_frac=float(np.mean(x > 0)),
                                 share_of_total_adv=float(x.sum() / total) if total else np.nan,
                                 share_of_conditions=len(x) / len(adv_all)))
            if metric == 'delta_rmse':
                cs = list(adv_all)
                x = np.array([adv_all[c] for c in cs])
                order = np.argsort(-x)
                eff = [mby[c]['effect_rms'] for c in cs]
                conc.append(dict(
                    other=other, ref=ref, n=len(x), total_adv_sum=float(x.sum()), mean_adv=float(x.mean()),
                    top5_share=float(x[order[:5]].sum() / x.sum()) if x.sum() else np.nan,
                    top10_share=float(x[order[:10]].sum() / x.sum()) if x.sum() else np.nan,
                    top5_conditions=','.join(cs[i] for i in order[:5]),
                    n_ref_better=int((x > 0).sum()),
                    **{f'spearman_effect_{k}': v for k, v in spear(x, eff).items()},
                    **{f'spearman_relative_adv_vs_effect_{k}': v for k, v in
                       spear(x / np.array(eff), eff).items()},
                    **{f'spearman_ncells_{k}': v for k, v in spear(x, [mby[c]['n_cells'] for c in cs]).items()},
                    **{f'spearman_nearest_train_corr_{k}': v for k, v in
                       spear(x, [mby[c]['nearest_train_response_corr'] for c in cs]).items()}))
    save(out / 'A1_paired_subgroups.tsv', rows)
    save(out / 'A1_concentration.tsv', conc)
    return summ, rows, conc


