#!/usr/bin/env Rscript
args <- commandArgs(trailingOnly=TRUE)
if (length(args) != 2L) stop("Usage: collect_phh.R RMA_DIR OUT_DIR")
paths <- sort(list.files(args[[1L]], pattern="\\.rds$", full.names=TRUE))
if (!length(paths)) stop("No assay contrasts found")
if (!dir.create(args[[2L]], recursive=TRUE)) stop("Expected a new output directory")
objects <- unlist(lapply(paths, readRDS), recursive=FALSE)
rows <- do.call(rbind, lapply(objects, function(x) x$meta))
values <- lapply(objects, function(x) x$delta)
symbols <- Reduce(intersect, lapply(values, names))
expr <- do.call(rbind, lapply(values, function(x) x[symbols]))
stopifnot(nrow(expr) == nrow(rows), all(is.finite(expr)), length(symbols) > 10000)
write.table(rows, file.path(args[[2L]], "rows.tsv"), sep="\t", quote=FALSE, row.names=FALSE, na="NA")
write.table(data.frame(symbol=symbols), file.path(args[[2L]], "genes.tsv"), sep="\t", quote=FALSE, row.names=FALSE)
con <- file(file.path(args[[2L]], "delta.f32"), "wb")
writeBin(as.vector(t(expr)), con, size=4L, endian="little")
close(con)
